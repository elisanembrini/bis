from enum import StrEnum

from pydantic import BaseModel


class ErrorCode(StrEnum):
    INVALID_CREDENTIALS = "INVALID_CREDENTIALS"
    TOO_MANY_ATTEMPTS = "TOO_MANY_ATTEMPTS"
    EMAIL_ALREADY_REGISTERED = "EMAIL_ALREADY_REGISTERED"
    RESET_TOKEN_INVALID = "RESET_TOKEN_INVALID"
    UNAUTHENTICATED = "UNAUTHENTICATED"
    GOOGLE_UNAVAILABLE = "GOOGLE_UNAVAILABLE"
    GOOGLE_STATE_INVALID = "GOOGLE_STATE_INVALID"
    GOOGLE_CANCELLED = "GOOGLE_CANCELLED"
    GOOGLE_EMAIL_NOT_VERIFIED = "GOOGLE_EMAIL_NOT_VERIFIED"
    GOOGLE_ACCOUNT_CONFLICT = "GOOGLE_ACCOUNT_CONFLICT"
    GOOGLE_FAILED = "GOOGLE_FAILED"
    INVITE_NOT_FOUND = "INVITE_NOT_FOUND"
    INVITE_EXPIRED = "INVITE_EXPIRED"
    INVITE_USED = "INVITE_USED"
    ALREADY_IN_HOUSEHOLD = "ALREADY_IN_HOUSEHOLD"
    MUST_LEAVE_HOUSEHOLD = "MUST_LEAVE_HOUSEHOLD"
    OWNER_CANNOT_LEAVE = "OWNER_CANNOT_LEAVE"
    NOT_HOUSEHOLD_OWNER = "NOT_HOUSEHOLD_OWNER"
    MEMBER_NOT_FOUND = "MEMBER_NOT_FOUND"
    CANNOT_REMOVE_SELF = "CANNOT_REMOVE_SELF"
    RECIPE_NOT_FOUND = "RECIPE_NOT_FOUND"
    PHOTO_TOO_LARGE = "PHOTO_TOO_LARGE"
    PHOTO_INVALID = "PHOTO_INVALID"
    PHOTO_NOT_FOUND = "PHOTO_NOT_FOUND"
    PHOTO_NOT_AVAILABLE = "PHOTO_NOT_AVAILABLE"


class ErrorResponse(BaseModel):
    code: ErrorCode
    message: str
